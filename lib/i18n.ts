const i18n = new I18n(translations);

const listeners = new Set<() => void>();

const getDeviceLanguage = (): Language => {
  const locales = Localization.getLocales();
  const languageCode = locales?.[0]?.languageCode?.toLowerCase();

  if (languageCode === 'en') return 'en';
  return 'de';
};

i18n.enableFallback = true;
i18n.defaultLocale = 'de';
i18n.locale = getDeviceLanguage();

const notifyLanguageChange = () => {
  listeners.forEach((listener) => listener());
};

export const getLanguage = (): Language => {
  const locale = String(i18n.locale).toLowerCase();
  return locale === 'en' ? 'en' : 'de';
};

export const subscribeLanguageChange = (listener: () => void) => {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
};

export const setLanguage = (lang: Language) => {
  i18n.locale = lang;
  notifyLanguageChange();
};

export const loadLanguage = async () => {
  try {
    const savedLang = await AsyncStorage.getItem(STORAGE_KEYS.APP_LANGUAGE);

    if (savedLang === 'de' || savedLang === 'en') {
      i18n.locale = savedLang;
    } else {
      i18n.locale = getDeviceLanguage();
    }
  } catch (error) {
    console.error('Fehler beim Laden der Sprache:', error);
    i18n.locale = getDeviceLanguage();
  } finally {
    notifyLanguageChange();
  }
};

export const useLanguage = () => {
  const [language, setLanguageState] = useState<Language>(getLanguage());

  useEffect(() => {
    const unsubscribe = subscribeLanguageChange(() => {
      setLanguageState(getLanguage());
    });

    return unsubscribe;
  }, []);

  return language;
};

export default i18n;
